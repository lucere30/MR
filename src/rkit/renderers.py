"""Output adapters own capabilities, DNS policy and wire formats."""
from collections import defaultdict
import json

import yaml

from .model import DOMAIN_TYPES, TARGET_IP_TYPES, TEXT_TYPES

CAPABILITIES = {
    "loon": DOMAIN_TYPES | {"IP-CIDR", "IP-CIDR6"} | TEXT_TYPES,
    "mihomo": DOMAIN_TYPES | TARGET_IP_TYPES | {"SRC-IP-CIDR", "PROCESS-NAME"},
    "singbox": DOMAIN_TYPES | {"IP-CIDR", "IP-CIDR6", "SRC-IP-CIDR"},
}
FIELDS = {"DOMAIN": "domain", "DOMAIN-SUFFIX": "domain_suffix",
          "DOMAIN-KEYWORD": "domain_keyword", "IP-CIDR": "ip_cidr",
          "IP-CIDR6": "ip_cidr", "SRC-IP-CIDR": "source_ip_cidr"}
OUTPUT_DIRS = {"loon": "lq/generated", "mihomo": "cat", "singbox": "singbox"}
EXTENSIONS = {"loon": "list", "mihomo": "yaml", "singbox": "json"}


def planned_paths(target, name, layout="combined", purpose="route"):
    if target == "singbox":
        suffixes = ["_domain", "_ip"]
    elif layout == "split" and purpose != "fakeip":
        suffixes = ["_domain", "_ip", "_other"]
    else:
        suffixes = [""]
    return [f"{OUTPUT_DIRS[target]}/{name}{suffix}.{EXTENSIONS[target]}" for suffix in suffixes]


def classical_line(rule):
    suffix = ",no-resolve" if rule.kind in TARGET_IP_TYPES else ""
    return f"{rule.kind},{rule.value}{suffix}"


def category(rule):
    if rule.kind in DOMAIN_TYPES:
        return "domain"
    if rule.kind in TARGET_IP_TYPES or rule.kind == "SRC-IP-CIDR":
        return "ip"
    return "other"


def yaml_payload(values):
    # JSON strings are valid YAML scalars; no quoting or whitespace ambiguity.
    text = "payload:\n" + "".join(f"  - {json.dumps(v, ensure_ascii=False)}\n" for v in values)
    if yaml.safe_load(text) != {"payload": values}:
        raise ValueError("YAML serialization failed")
    return text


def render(rules, target, name, *, purpose="route", layout="combined", omit=()):
    if purpose == "fakeip":
        if target != "mihomo" or any(r.kind not in {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-PATTERN"} for r in rules):
            raise ValueError("Fake-IP requires a Mihomo domain payload")
        values = ["+." + r.value if r.kind == "DOMAIN-SUFFIX" else r.value for r in rules]
        return {f"cat/{name}.yaml": yaml_payload(values)}, []
    skipped = [r for r in rules if r.kind not in CAPABILITIES[target]]
    forbidden = [r for r in skipped if r.kind not in omit]
    if forbidden:
        r = forbidden[0]
        raise ValueError(f"{r.location}: {target} cannot represent {r.kind}; configure an explicit omission or change targets")
    accepted = [r for r in rules if r.kind in CAPABILITIES[target]]
    if not accepted:
        raise ValueError(f"{target}: no representable rules")
    reports = [{"source": r.source, "line": r.line, "type": r.kind, "value": r.value} for r in skipped]
    return RENDERERS[target](accepted, name, layout), reports


def render_singbox(accepted, name, layout):
    output = {}
    for group in ("domain", "ip"):
        fields = defaultdict(set)
        for r in accepted:
            if category(r) == group:
                fields[FIELDS[r.kind]].add(r.value)
        # Separate objects preserve OR semantics across different fields.
        data = {"version": 2, "rules": [{field: sorted(values)} for field, values in sorted(fields.items())]}
        output[f"singbox/{name}_{group}.json"] = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    return output


def render_text(accepted, name, layout, *, target):
    groups = {"": accepted} if layout == "combined" else {
        "_" + group: [r for r in accepted if category(r) == group] for group in ("domain", "ip", "other")
    }
    output = {}
    for suffix, values in groups.items():
        if not values:
            continue
        lines = [classical_line(r) for r in values]
        if target == "loon":
            output[f"lq/generated/{name}{suffix}.list"] = "# Generated by rkit; edit inputs, not this file.\n" + "\n".join(lines) + "\n"
        else:
            output[f"cat/{name}{suffix}.yaml"] = yaml_payload(lines)
    return output


RENDERERS = {
    "loon": lambda rules, name, layout: render_text(rules, name, layout, target="loon"),
    "mihomo": lambda rules, name, layout: render_text(rules, name, layout, target="mihomo"),
    "singbox": render_singbox,
}
